// testable — есть ли у специализации собственный банк заданий: тот же порог, что у сервиса
// тестирования, поэтому новые банки (QA, ИБ) сид подхватывает без правок.
func testable(spec string) bool {
	n := 0
	for _, f := range itembank.BySpec(itembank.Spec(spec)) {
		if f.Meta().Spec != itembank.SpecCommon {
			n++
		}
	}
	return n >= apptesting.DefaultMinSpecFamilies
}

